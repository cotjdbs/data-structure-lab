def count_stages(concerts):
    """콘서트장의 무대 공간 개수를 BFS를 이용하여 반환하는 함수입니다.
    입력으로 주어지는 `concerts` 2차원 배열은 콘서트장의 배치도를 나타냅니다.
    여기서 1은 펜스가 위치한 공간을, 0은 무대가 설치될 수 있는 빈 공간을 의미합니다.
    연결된 0 공간들은 하나의 무대 공간으로 인식하며, 이 함수는 이러한 독립적인 무대 공간의 총 개수를 계산합니다.

    이 함수는 너비 우선 탐색(BFS)을 사용하여 각 무대 공간을 식별하고 카운트합니다.
    큐를 활용하여 시작 지점에서 가까운 칸부터 탐색을 시작하며, 연결된 모든 0 공간은 하나의 무대 공간으로 간주하여 탐색 완료 시 전체를 방문 처리합니다.
    중복 탐색을 방지하기 위해 `visited` 배열을 사용하여 이미 방문한 칸은 즉시 표시합니다.
    전체 그리드를 반복하면서 아직 방문하지 않은 0을 발견하면 BFS를 실행하고, 무대 공간의 개수를 1 증가시킵니다.
    최종적으로 BFS가 실행된 횟수가 독립적인 무대 공간의 총 개수가 됩니다.
    """
    N = len(concerts) # 콘서트장 배열의 행(높이) 개수를 선언합니다.
    M = len(concerts[0]) # 콘서트장 배열의 열(너비) 개수를 선언합니다.
    answer = 0 # 발견된 독립적인 무대 공간의 총 개수를 저장할 변수를 초기화합니다.
    visited = [[False] * M for _ in range(N)] # 모든 칸의 방문 여부를 추적하기 위한 2차원 배열을 초기화합니다. 처음에는 모든 칸을 방문하지 않은 상태로 설정합니다.

    directions = [(-1, 0), (1, 0), (0, -1), (0, 1)] # 상하좌우 네 방향으로 이동하기 위한 행과 열의 변화량을 정의합니다.

    # DFS가 아닌 BFS를 사용합니다. 시간 복잡도 상의 큰 차이는 없지만, 직관적인 구현을 위해 BFS를 선택합니다.
    def bfs(start_r, start_c):
        """주어진 시작점에서 연결된 모든 0 공간을 탐색하고 방문 처리하는 내부 BFS 함수입니다.
        이 함수는 하나의 독립된 무대 공간을 찾아 방문 처리하는 역할을 수행합니다.
        """
        queue = [(start_r, start_c)] # BFS 탐색을 위한 큐를 초기화하고 시작 지점을 추가합니다.
        visited[start_r][start_c] = True # 시작 지점을 방문했음으로 표시합니다.

        while queue:
            r, c = queue.pop(0) # 큐의 맨 앞에서 현재 탐색할 좌표 (행, 열)를 꺼냅니다.

            # 현재 좌표에서 네 방향(상하좌우)으로 이동할 다음 좌표를 계산하고 탐색합니다.
            for dr, dc in directions:
                nr, nc = r + dr, c + dc # 다음 이동할 행(nr)과 열(nc) 좌표를 계산합니다.

                # 다음 좌표가 콘서트장 배열의 유효한 범위 내에 있고,
                # 아직 방문하지 않았으며, 해당 칸이 무대 공간(값 0)인 경우에만 이동을 수행합니다.
                if 0 <= nr < N and 0 <= nc < M and not visited[nr][nc] and concerts[nr][nc] == 0:
                    queue.append((nr, nc)) # 다음 탐색을 위해 해당 좌표를 큐에 추가합니다.
                    visited[nr][nc] = True # 큐에 추가된 대상을 중복 방문하는 것을 방지하기 위해 방문했음으로 즉시 표시합니다.

    # 콘서트장 배열의 모든 칸을 순회하며 독립적인 무대 공간을 찾습니다.
    for r in range(N):
        for c in range(M):
            # 만약 현재 칸이 아직 방문하지 않은 무대 공간(값 0)인 경우,
            # 이는 새로운 독립적인 무대 공간의 시작점을 의미합니다.
            if not visited[r][c] and concerts[r][c] == 0:
                bfs(r, c) # 해당 칸부터 시작하여 연결된 모든 무대 공간을 탐색하고 방문 처리합니다.
                answer += 1 # 새로운 무대 공간을 발견했으므로 무대 공간의 총 개수를 1 증가시킵니다.

    return answer # 최종적으로 계산된 독립적인 무대 공간의 총 개수를 반환합니다.

print(count_stages(concerts))